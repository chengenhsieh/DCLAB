module ps2_key_tracker (
    input  wire         i_clk, 
    input  wire         i_rst, 
    input  wire         i_start,      // 啟動訊號
    input  wire         i_valid_in,   // PS/2資料是否有效 (來自ps2_rx)
    input  wire [7:0]   i_ps2_data,
    output reg  [11:0]  o_key_vector,
    output reg          o_up_octave,
    output reg          o_down_octave
);
    parameter [7:0] SC_PGUP = 8'h6F, SC_PGDN = 8'h6D;
    parameter [7:0] SC_A = 8'h1C, SC_W = 8'h1D, SC_S = 8'h1B, SC_E = 8'h24;
    parameter [7:0] SC_D = 8'h23, SC_F = 8'h2B, SC_T = 8'h2C, SC_G = 8'h34;
    parameter [7:0] SC_Y = 8'h35, SC_H = 8'h33, SC_U = 8'h3C, SC_J = 8'h3B;

    localparam S_IDLE = 2'b00;
    localparam S_MAKE = 2'b01;
    localparam S_BREAK = 2'b10;
    localparam S_BREAK_BUF = 2'b11;
    reg [1:0] state_r, state_w;
    reg [11:0] key_vector_w;
    reg up_octave_r, up_octave_w, down_octave_r, down_octave_w;
    assign o_up_octave = up_octave_r;
    assign o_down_octave = down_octave_r;

    always @(*) begin
        case (state_r)
            S_IDLE: begin
                if (i_start) state_w = S_MAKE;
                else state_w = S_IDLE;
            end
            S_MAKE: begin
                if (i_valid_in == 1'b1 && i_ps2_data == 8'hF0) state_w = S_BREAK;
                else state_w = S_MAKE;
            end
            S_BREAK:
                if (i_valid_in) state_w = S_BREAK_BUF;
                else state_w = S_BREAK;
            S_BREAK_BUF:
                state_w = S_MAKE;
            default: state_w = S_IDLE;
        endcase
    end

    always @(*) begin
        key_vector_w = o_key_vector;
        case (state_r)
            S_IDLE: begin
                key_vector_w = 12'd0; 
            end
            S_MAKE: begin
                if (i_valid_in) begin
                    case (i_ps2_data)
                        SC_PGUP: up_octave_w = 1'b1;
                        SC_PGDN: down_octave_w = 1'b1;
                        SC_A: key_vector_w[0] = 1'b1;
                        SC_W: key_vector_w[1] = 1'b1;
                        SC_S: key_vector_w[2] = 1'b1;
                        SC_E: key_vector_w[3] = 1'b1;
                        SC_D: key_vector_w[4] = 1'b1;
                        SC_F: key_vector_w[5] = 1'b1;
                        SC_T: key_vector_w[6] = 1'b1;
                        SC_G: key_vector_w[7] = 1'b1;
                        SC_Y: key_vector_w[8] = 1'b1;
                        SC_H: key_vector_w[9] = 1'b1;
                        SC_U: key_vector_w[10] = 1'b1;
                        SC_J: key_vector_w[11] = 1'b1;
                        default: ; // 非指定鍵，保持 key_vector_w 不變
                    endcase
                end
            end
            S_BREAK: begin
                if (i_valid_in) begin
                    case (i_ps2_data)
                        SC_PGUP: up_octave_w = 1'b0;
                        SC_PGDN: down_octave_w = 1'b0;
                        SC_A: key_vector_w[0] = 1'b0;
                        SC_W: key_vector_w[1] = 1'b0;
                        SC_S: key_vector_w[2] = 1'b0;
                        SC_E: key_vector_w[3] = 1'b0;
                        SC_D: key_vector_w[4] = 1'b0;
                        SC_F: key_vector_w[5] = 1'b0;
                        SC_T: key_vector_w[6] = 1'b0;
                        SC_G: key_vector_w[7] = 1'b0;
                        SC_Y: key_vector_w[8] = 1'b0;
                        SC_H: key_vector_w[9] = 1'b0;
                        SC_U: key_vector_w[10] = 1'b0;
                        SC_J: key_vector_w[11] = 1'b0;
                        default: ; // 非指定鍵，保持 key_vector_w 不變
                    endcase 
                end
            end
            S_BREAK_BUF: ; // 保持 key_vector_w 不變
            default: key_vector_w = 12'd0; 
        endcase
    end

    always_ff @(posedge i_clk or posedge i_rst) begin
        if (i_rst) begin
            state_r       <= S_IDLE;
            o_key_vector  <= 12'd0;
            up_octave_r   <= 1'b0;
            down_octave_r <= 1'b0;
        end 
        else begin
            state_r <= state_w;
            if (i_valid_in) begin
                o_key_vector <= key_vector_w;
            end
            up_octave_r   <= up_octave_w;
            down_octave_r <= down_octave_w;
        end
    end
endmodule

module top (
    input  wire        i_clk,
    input  wire        i_rst,
    input  wire        i_start,
    input  wire        i_valid_in,
    input  wire [7:0]  i_ps2_data,
    output reg signed [15:0] o_audio_sample
);
    wire [11:0] o_key_vector;
    reg up_octave, down_octave;
    ps2_key_tracker ps2 (
        .i_clk         (i_clk),
        .i_rst         (i_rst),
        .i_start       (i_start),
        .i_valid_in    (i_valid_in),
        .i_ps2_data    (i_ps2_data),
        .o_key_vector  (o_key_vector),
        .o_up_octave   (up_octave),
        .o_down_octave (down_octave)
    );

    reg [2:0] octave;

    wire signed [15:0] audio_samples [0:11];
    reg signed [19:0] audio_samples_sum;
    reg [3:0] active_count;

    integer i;
    always @(*) begin
        audio_samples_sum = 20'd0;
        active_count = 4'd0;
        for (i = 0; i < 12; i = i + 1) begin
            audio_samples_sum = audio_samples_sum + audio_samples[i];
        end
        o_audio_sample = audio_samples_sum[17:2];
    end

    wire [31:0] phase_incs [0:11];
    assign phase_incs[0]  = 32'd22473502; // C
    assign phase_incs[1]  = 32'd23809838; // C#
    assign phase_incs[2]  = 32'd25225631; // D
    assign phase_incs[3]  = 32'd26725606; // D#
    assign phase_incs[4]  = 32'd28314830; // E
    assign phase_incs[5]  = 32'd29998457; // F
    assign phase_incs[6]  = 32'd31782243; // F#
    assign phase_incs[7]  = 32'd33672114; // G
    assign phase_incs[8]  = 32'd35674428; // G#
    assign phase_incs[9]  = 32'd37795712; // A
    assign phase_incs[10] = 32'd40043183; // A#
    assign phase_incs[11] = 32'd42424227; // B
    genvar j;
    generate
        for (j = 0; j < 12; j = j + 1) begin : gen_sin
            generator_sin gen_sin (
            .i_clk      (i_clk),
            .i_rst      (i_rst),
            .i_start    (i_start),
            .i_play     (o_key_vector[j]),
            .i_phase_inc(phase_incs[j] * 2**(octave-3'b100)),
            .o_sin      (audio_samples[j])
            );
        end
    endgenerate

    always_ff @(posedge i_rst or posedge up_octave or posedge down_octave) begin
        if (i_rst) begin
            octave <= 3'b100;
        end 
        else if (up_octave) begin
            if (octave == 3'b111) ;
            else octave <= octave + 3'b001; 
        end
        else if (down_octave) begin
            if (octave == 3'b001) ;
            else octave <= octave - 3'b001; 
        end
    end
endmodule

module generator_sin (
  input                i_clk,
  input                i_rst,
  input                i_start,
  input                i_play,
  input         [31:0] i_phase_inc,                
  output signed [15:0] o_sin
);

    reg [2:0] state_r, state_w;
    localparam S_IDLE    = 3'd0;
    localparam S_START   = 3'd1;
    localparam S_RISE    = 3'd2;
    localparam S_DECAY   = 3'd3;
    localparam S_RELEASE = 3'd4;

    reg signed [15:0] sin_r, sin_w, sin_mid;
    reg [31:0] amp_coe_r, amp_coe_w;
    reg [55:0] amp_coe_temp;

    reg signed [31:0] o_sin_temp;
    assign o_sin_temp = sin_r * $signed({1'b0, amp_coe_r[31:16]});
    assign o_sin = o_sin_temp[31:16];

    reg [31:0] phase_r, phase_w; // oo oooooooooo ooooooooooooooooooo 
    wire [1:0] quadrant = phase_r[31:30];
    wire [9:0] addr     = phase_r[29:20];
    reg [9:0] true_addr;

    always @(*) begin
        case (state_r)
            S_IDLE:  amp_coe_w = 32'd0;
            S_START: amp_coe_w = 32'd0;
            S_RISE:  amp_coe_w = amp_coe_r + 32'd4294967;
            S_DECAY: begin
                amp_coe_temp = amp_coe_r * 24'd16777115;
                amp_coe_w    = amp_coe_temp[55:24];
            end
            S_RELEASE: begin
                if (amp_coe_r > 32'd214748) amp_coe_w = amp_coe_r - 32'd214748;
                else amp_coe_w = 32'd0;
            end
            default: amp_coe_w = 32'd0;
        endcase
    end

    always @(*) begin
        case (state_r)
            S_IDLE: begin
                if (i_start) state_w = S_START;
                else state_w = S_IDLE;
            end
            S_START: begin
                if (i_play) state_w = S_RISE;
                else state_w = S_START;
            end
            S_RISE: begin
                if (amp_coe_r >= 32'd4286377066) state_w = S_DECAY;
                else if (!i_play) state_w = S_RELEASE;
                else state_w = S_RISE;
            end
            S_DECAY: begin
                if (!i_play) state_w = S_RELEASE;
                else state_w = S_DECAY;
            end
            S_RELEASE: begin
                if (i_play) state_w = S_RISE;
                else if (amp_coe_r == 32'd0) state_w = S_START;
            end
            default: state_w = S_IDLE;
        endcase
    end

    always @(*) begin
        phase_w = phase_r + i_phase_inc;
    end

    always @(*) begin
        if (quadrant==2'b01 || quadrant==2'b11) true_addr = 1023 - addr;
        else true_addr = addr; 
        if (quadrant==2'b10 || quadrant==2'b11) sin_w = -sin_mid;
        else sin_w = sin_mid;
    end
    sin_1024 s2(.addr(true_addr), .sin(sin_mid));

    always @(posedge i_clk or posedge i_rst) begin
        if (i_rst) begin
            state_r   <= S_IDLE;
            phase_r   <= 32'd0;
            sin_r     <= 16'd0;
            amp_coe_r <= 32'd0;
        end 
        else begin
            state_r   <= state_w;
            phase_r   <= phase_w;
            sin_r     <= sin_w;
            amp_coe_r <= amp_coe_w;
        end
    end
endmodule

